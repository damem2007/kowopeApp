-- Kowope PostgreSQL baseline v1 (derived from the final SQLite schema after migration 33).
-- Run on a new, EMPTY PostgreSQL database. Never run the SQLite migration history here.
-- Existing text IDs stay TEXT to preserve historical identifiers; new UUID strings are valid TEXT.
-- Legacy integer flags remain SMALLINT (0/1) for compatible API JSON/branch behavior.
-- REAL amounts remain DOUBLE PRECISION to avoid silently rounding existing values.
-- For exact money math, migrate to fixed decimal with an audited business-logic change later.

BEGIN;
CREATE TABLE IF NOT EXISTS users (
  id TEXT PRIMARY KEY, email TEXT NOT NULL UNIQUE, password_hash TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), role TEXT NOT NULL DEFAULT 'user',
  email_verified_at TIMESTAMPTZ, last_login_at TIMESTAMPTZ, suspended_at TIMESTAMPTZ
);
CREATE TABLE IF NOT EXISTS organizations (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS organization_members (
  organization_id INTEGER NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  membership_role TEXT NOT NULL DEFAULT 'member',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (organization_id, user_id), UNIQUE (user_id)
);
CREATE TABLE IF NOT EXISTS clients (
  id TEXT PRIMARY KEY, name TEXT NOT NULL, email TEXT NOT NULL UNIQUE,
  company TEXT, phone TEXT, notes TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), address TEXT DEFAULT '',
  organization_id INTEGER REFERENCES organizations(id),
  created_by_user_id TEXT REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS business_profile (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL DEFAULT '', address TEXT NOT NULL DEFAULT '',
  email TEXT NOT NULL DEFAULT '', phone TEXT NOT NULL DEFAULT '',
  payment_instructions TEXT NOT NULL DEFAULT '',
  invoice_prefix TEXT NOT NULL DEFAULT 'INV-', invoice_number_padding INTEGER NOT NULL DEFAULT 4,
  invoice_number_format TEXT NOT NULL DEFAULT '{PREFIX}{YYYY}-{NUMBER}',
  preferred_email_provider TEXT, default_currency TEXT NOT NULL DEFAULT 'USD',
  allow_user_signup SMALLINT NOT NULL DEFAULT 0,
  organization_id INTEGER REFERENCES organizations(id),
  user_id TEXT REFERENCES users(id), logo_data_url TEXT DEFAULT NULL
);
CREATE TABLE IF NOT EXISTS currencies (
  code TEXT NOT NULL, user_id TEXT REFERENCES users(id),
  organization_id INTEGER REFERENCES organizations(id), name TEXT NOT NULL,
  sign TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS currencies_global_code ON currencies(code) WHERE user_id IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS currencies_user_code ON currencies(code, user_id) WHERE user_id IS NOT NULL;
CREATE TABLE IF NOT EXISTS integrations (
  provider TEXT PRIMARY KEY, status TEXT NOT NULL DEFAULT 'not_connected',
  account_label TEXT, config_json TEXT NOT NULL DEFAULT '{}',
  connected_at TIMESTAMPTZ, last_error TEXT,
  organization_id INTEGER REFERENCES organizations(id), user_id TEXT REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS invoices (
  id TEXT PRIMARY KEY, number TEXT NOT NULL UNIQUE,
  client_name TEXT NOT NULL, client_email TEXT NOT NULL, description TEXT NOT NULL,
  amount DOUBLE PRECISION NOT NULL, currency TEXT NOT NULL DEFAULT 'USD',
  subtotal_amount DOUBLE PRECISION NOT NULL DEFAULT 0,
  discount_value DOUBLE PRECISION NOT NULL DEFAULT 0,
  discount_type TEXT NOT NULL DEFAULT '%' CHECK (discount_type IN ('%', '$')),
  discount_amount DOUBLE PRECISION NOT NULL DEFAULT 0,
  tax_name TEXT NOT NULL DEFAULT 'Tax', tax_rate DOUBLE PRECISION NOT NULL DEFAULT 0,
  tax_amount DOUBLE PRECISION NOT NULL DEFAULT 0,
  payment_instructions TEXT NOT NULL DEFAULT '', due_date TEXT,
  status TEXT NOT NULL DEFAULT 'Draft', created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  sent_at TIMESTAMPTZ, client_id TEXT REFERENCES clients(id),
  schedule_id INTEGER,
  is_past SMALLINT NOT NULL DEFAULT 0,
  issue_date TEXT, paid_at TIMESTAMPTZ,
  organization_id INTEGER REFERENCES organizations(id), user_id TEXT REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS recurring_schedules (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id TEXT NOT NULL REFERENCES clients(id), business_id INTEGER,
  description TEXT NOT NULL, frequency TEXT NOT NULL,
  currency_code TEXT NOT NULL DEFAULT 'USD', status TEXT NOT NULL DEFAULT 'active',
  next_run_at TIMESTAMPTZ NOT NULL, end_at TEXT,
  auto_send SMALLINT NOT NULL DEFAULT 0,
  source_invoice_id TEXT REFERENCES invoices(id) DEFERRABLE INITIALLY DEFERRED,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  organization_id INTEGER REFERENCES organizations(id), user_id TEXT REFERENCES users(id)
);
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'invoices_schedule_id_fkey' AND conrelid = 'invoices'::regclass) THEN
    ALTER TABLE invoices ADD CONSTRAINT invoices_schedule_id_fkey
      FOREIGN KEY (schedule_id) REFERENCES recurring_schedules(id)
      DEFERRABLE INITIALLY DEFERRED;
  END IF;
END $$;
CREATE TABLE IF NOT EXISTS line_items (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_id TEXT NOT NULL REFERENCES invoices(id) ON DELETE CASCADE,
  description TEXT NOT NULL, quantity DOUBLE PRECISION NOT NULL DEFAULT 1,
  unit_price DOUBLE PRECISION NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS schedule_price_history (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  schedule_id INTEGER NOT NULL REFERENCES recurring_schedules(id) ON DELETE CASCADE,
  amount DOUBLE PRECISION NOT NULL, effective_from TEXT NOT NULL,
  price_change_note SMALLINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS payments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_id TEXT NOT NULL REFERENCES invoices(id), client_id TEXT REFERENCES clients(id),
  date TEXT NOT NULL, source TEXT NOT NULL DEFAULT 'Manual', method TEXT,
  amount DOUBLE PRECISION NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  organization_id INTEGER REFERENCES organizations(id), user_id TEXT REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS backup_settings (
  id INTEGER PRIMARY KEY CHECK (id = 1), recipient_email TEXT NOT NULL DEFAULT '',
  interval_days INTEGER NOT NULL DEFAULT 14, enabled SMALLINT NOT NULL DEFAULT 1,
  last_sent_at TIMESTAMPTZ, next_run_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS security_settings (
  id INTEGER PRIMARY KEY CHECK (id = 1), reset_token_minutes INTEGER NOT NULL DEFAULT 15,
  password_min_length INTEGER NOT NULL DEFAULT 12,
  require_uppercase SMALLINT NOT NULL DEFAULT 0, require_lowercase SMALLINT NOT NULL DEFAULT 0,
  require_number SMALLINT NOT NULL DEFAULT 0, require_symbol SMALLINT NOT NULL DEFAULT 0,
  configured_at TIMESTAMPTZ
);
CREATE TABLE IF NOT EXISTS email_verification_tokens (
  token_hash TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at TIMESTAMPTZ NOT NULL, used_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS auth_sessions (
  token TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at TIMESTAMPTZ NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_auth_sessions_user ON auth_sessions(user_id);
CREATE INDEX IF NOT EXISTS idx_auth_sessions_expiry ON auth_sessions(expires_at);
CREATE TABLE IF NOT EXISTS guest_analytics (
  id TEXT PRIMARY KEY, account_key TEXT NOT NULL DEFAULT 'guest',
  session_id TEXT NOT NULL, event TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_guest_analytics_session ON guest_analytics(session_id);
CREATE TABLE IF NOT EXISTS email_templates (
  id TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  template_key TEXT NOT NULL, subject TEXT NOT NULL, body TEXT NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), UNIQUE(user_id, template_key)
);
CREATE TABLE IF NOT EXISTS platform_email_templates (
  id TEXT PRIMARY KEY, template_key TEXT NOT NULL UNIQUE,
  subject TEXT NOT NULL, body TEXT NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS postgres_schema_migrations (
  version INTEGER PRIMARY KEY, applied_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  description TEXT NOT NULL
);
